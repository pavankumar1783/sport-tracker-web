import { ChangeDetectionStrategy, Component, computed, effect, inject, untracked } from '@angular/core';
import { Sport, TournamentStages } from '../../../core/models/api.models';
import { humanizeEnum } from '../../../core/models/enums';
import { SportsApi } from '../../../core/services/api/sports.api';
import { TournamentsApi } from '../../../core/services/api/tournaments.api';
import { AsyncState } from '../../../core/state/async-state';
import { EmptyStateComponent } from '../../../shared/components/empty-state/empty-state.component';
import { ErrorStateComponent } from '../../../shared/components/error-state/error-state.component';
import { SkeletonComponent } from '../../../shared/components/skeleton/skeleton.component';
import { StatusBadgeComponent } from '../../../shared/components/status-badge/status-badge.component';
import { ConfigureFormatFormComponent } from '../components/configure-format-form.component';
import { TournamentContext } from '../tournament-context.service';
import { canConfigureFormat } from '../tournament-logic';

@Component({
  selector: 'st-tournament-stages-page',
  imports: [
    StatusBadgeComponent,
    EmptyStateComponent,
    ErrorStateComponent,
    SkeletonComponent,
    ConfigureFormatFormComponent,
  ],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    @if (stages.error(); as error) {
      <st-error-state [error]="error" (retry)="load()" />
    } @else if (stages.data(); as data) {
      <div class="stack stack--lg">
        @if (showForm(); as tournament) {
          @if (sports.data()) {
            <st-configure-format-form
              [tournament]="tournament"
              [sportFormats]="sportFormats()"
              (configured)="onConfigured()"
            />
          }
        }

        @if (data.stages.length === 0) {
          <div class="card">
            <st-empty-state
              icon="list"
              title="No stages yet"
              [message]="
                context.canManage()
                  ? 'Choose a format above to create the tournament stages.'
                  : 'The organizer has not chosen a format for this tournament yet.'
              "
            />
          </div>
        } @else {
          <ol class="card card--flush list stages">
            @for (stage of data.stages; track stage.id) {
              <li>
                <span class="seq">{{ stage.sequence }}</span>
                <div class="grow">
                  <strong class="truncate who">{{ stage.name }}</strong>
                  <span class="muted small">{{ label(stage.stageType) }}</span>
                </div>
                <st-status-badge [status]="stage.status" />
              </li>
            }
          </ol>
          <p class="muted small">Knockout brackets and winner advancement are not generated by the backend yet.</p>
        }
      </div>
    } @else {
      <div class="card" aria-busy="true"><st-skeleton [rows]="3" height="22px" /></div>
    }
  `,
  styles: `
    .stages li {
      min-width: 0;
    }
    .who {
      display: block;
    }
    .seq {
      display: grid;
      place-items: center;
      flex: none;
      width: 32px;
      height: 32px;
      border-radius: 50%;
      background: var(--c-primary-soft);
      color: var(--c-primary);
      font-weight: 700;
    }
    .grow {
      display: flex;
      flex-direction: column;
    }
  `,
})
export class StagesPage {
  private readonly api = inject(TournamentsApi);
  private readonly sportsApi = inject(SportsApi);
  protected readonly context = inject(TournamentContext);

  protected readonly stages = new AsyncState<TournamentStages>();
  protected readonly sports = new AsyncState<Sport[]>();

  protected readonly sportFormats = computed(() => {
    const tournament = this.context.state.data();
    return this.sports.data()?.find((sport) => sport.id === tournament?.sportId)?.formats ?? [];
  });

  /** The tournament when the organizer may still choose its format, otherwise null. */
  protected readonly showForm = computed(() => {
    const tournament = this.context.state.data();
    const stageCount = this.stages.data()?.stages.length ?? 0;
    return this.context.canManage() && tournament && canConfigureFormat(tournament.status, stageCount) ? tournament : null;
  });

  constructor() {
    effect(() => {
      if (this.context.id() !== null) {
        untracked(() => this.load());
      }
    });
    this.sports.load(this.sportsApi.getSports());
  }

  protected load(): void {
    const id = this.context.id();
    if (id !== null) {
      this.stages.load(this.api.getStages(id));
    }
  }

  protected label(value: string): string {
    return humanizeEnum(value);
  }

  protected onConfigured(): void {
    this.load();
    this.context.reload();
  }
}
